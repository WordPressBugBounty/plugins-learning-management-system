<?php
/**
 * Content partial for the native Divi 5 Course List module: the toggle CSS
 * and the course markup, wrapped by NativeModuleSupport::render().
 *
 * @package Masteriyo\Addons\DiviIntegration
 *
 * @var array  $attributes        Raw (undefaulted) block attributes.
 * @var string $instance_selector CSS selector unique to this module instance.
 * @var string $pagination_key    Pagination query parameter unique to this module instance.
 */

use Masteriyo\Addons\DiviIntegration\Helper;

defined( 'ABSPATH' ) || exit;

$posts_per_page  = absint( Helper::get_divi5_attr( $attributes, 'postsPerPage', 12 ) );
$columns         = absint( Helper::get_divi5_attr( $attributes, 'columns', 3 ) );
$sort_order      = sanitize_key( Helper::get_divi5_attr( $attributes, 'order', 'desc' ) );
$sort_order_by   = sanitize_key( Helper::get_divi5_attr( $attributes, 'orderBy', 'date' ) );
$show_pagination = 'on' === sanitize_key( Helper::get_divi5_attr( $attributes, 'show_pagination', 'off' ) );

$toggles = Helper::get_divi5_toggles( $attributes, Helper::COURSE_LIST_TOGGLE_SELECTORS );

// divi/select (multiple) stores a plain array of term IDs, so it goes straight into the tax_query.
$include_categories = (array) Helper::get_divi5_attr( $attributes, 'include_categories', array() );
$exclude_categories = (array) Helper::get_divi5_attr( $attributes, 'exclude_categories', array() );
?>
<?php
// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by render_toggle_hide_css() from a fixed selector list, no user-controlled markup.
echo Helper::render_toggle_hide_css( $instance_selector, $toggles, Helper::COURSE_LIST_TOGGLE_SELECTORS );
?>
<div class="et_pb_module_inner masteriyo-course-list-display-section">
	<?php
	// phpcs:disable WordPress.Security.EscapeOutput.OutputNotEscaped -- Template HTML from masteriyo_get_template_part(); the templates escape every field.
	echo Helper::render_course_list(
		array(
			'per_page'           => $posts_per_page,
			'columns'            => $columns,
			'order'              => $sort_order,
			'order_by'           => $sort_order_by,
			'include_categories' => $include_categories,
			'exclude_categories' => $exclude_categories,
			'show_pagination'    => $show_pagination,
			'pagination_key'     => $pagination_key,
		)
	);
	// phpcs:enable WordPress.Security.EscapeOutput.OutputNotEscaped
	?>
</div>
