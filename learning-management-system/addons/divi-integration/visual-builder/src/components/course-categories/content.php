<?php
/**
 * Content partial for the native Divi 5 Course Categories module: the toggle
 * CSS and the category markup, wrapped by NativeModuleSupport::render().
 *
 * @package Masteriyo\Addons\DiviIntegration
 *
 * @var array  $attributes        Raw (undefaulted) block attributes.
 * @var string $instance_selector CSS selector unique to this module instance.
 */

use Masteriyo\Addons\DiviIntegration\Helper;

defined( 'ABSPATH' ) || exit;

$categories_per_page    = absint( Helper::get_divi5_attr( $attributes, 'perPage', 12 ) );
$columns                = absint( Helper::get_divi5_attr( $attributes, 'columns', 3 ) );
$include_sub_categories = 'on' === sanitize_key( Helper::get_divi5_attr( $attributes, 'include_sub_categories', 'on' ) );
$sort_order_by          = sanitize_key( Helper::get_divi5_attr( $attributes, 'orderBy', 'name' ) );
$sort_order             = sanitize_key( Helper::get_divi5_attr( $attributes, 'order', 'asc' ) );

$toggles = Helper::get_divi5_toggles( $attributes, Helper::COURSE_CATEGORIES_TOGGLE_SELECTORS );
?>
<?php
// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by render_toggle_hide_css() from a fixed selector list, no user-controlled markup.
echo Helper::render_toggle_hide_css( $instance_selector, $toggles, Helper::COURSE_CATEGORIES_TOGGLE_SELECTORS );
?>
<div class="et_pb_module_inner">
	<?php
	// phpcs:disable WordPress.Security.EscapeOutput.OutputNotEscaped -- Template HTML from masteriyo_get_template(); the templates escape every field.
	echo Helper::render_course_categories_list(
		array(
			'per_page'               => $categories_per_page,
			'columns'                => $columns,
			'include_sub_categories' => $include_sub_categories,
			'order_by'               => $sort_order_by,
			'order'                  => $sort_order,
		)
	);
	// phpcs:enable WordPress.Security.EscapeOutput.OutputNotEscaped
	?>
</div>
